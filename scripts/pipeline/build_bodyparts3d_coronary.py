#!/usr/bin/env python3
"""
BodyParts3D 4.0 Coronary Centerline Processing Pipeline
Dataset Source: BodyParts3D 4.0 (c) Database Center for Life Science (DBCLS), CC BY 4.0
Converts clinical CT coronary centrelines and tapering radii to Three.js-calibrated coordinates.
"""

import json
import os
import math

SOURCE_CONTENT = '/Users/shehab/.gemini/antigravity/brain/786d7cbd-964e-41a9-bd43-b34a0ef2320a/.system_generated/steps/875/content.md'
OUTPUT_JSON = './public/data/bodyparts3d_coronary.json'
OUTPUT_TS = './src/data/bodyparts3dCoronary.ts'

SCALE_FACTOR = 28.0 # mm to Three.js scene units

def run_pipeline():
    print("[Pipeline] Reading extracted BodyParts3D dataset...")
    with open(SOURCE_CONTENT, 'r') as f:
        text = f.read()

    start = text.find('{')
    end = text.rfind('}') + 1
    raw = json.loads(text[start:end])

    meta = raw.get('meta', {})
    vessels = raw.get('vessels', [])
    print(f"[Pipeline] Processing {len(vessels)} authentic clinical coronary vessels...")

    processed_vessels = []
    
    # Clinical color palette for vessels
    color_map = {
        'lm': '#ef4444',
        'lad': '#f87171',
        'lcx': '#fb923c',
        'rca': '#38bdf8',
        'pda': '#0284c7',
        'rpl': '#38bdf8',
        'd1': '#f43f5e',
        'd2': '#fb7185',
        'om1': '#f97316',
        'om2': '#fb923c',
        's1': '#e11d48',
        's2': '#e11d48',
        'cb': '#60a5fa',
        'am': '#38bdf8'
    }

    for v in vessels:
        v_id = v.get('id')
        name = v.get('name')
        short = v.get('short', v_id.upper())
        system = 'LCA' if v.get('system') == 'left' else 'RCA'
        raw_points = v.get('points', [])
        raw_radii = v.get('radii', [])
        segments = v.get('segments', [])

        # Transform and scale points
        norm_points = []
        for p in raw_points:
            # BodyParts3D mm coordinates centered around isocentre
            # X: left (+), Y: superior (+), Z: anterior (+)
            nx = round(p[0] / SCALE_FACTOR, 4)
            ny = round(p[1] / SCALE_FACTOR, 4)
            nz = round(p[2] / SCALE_FACTOR, 4)
            norm_points.append([nx, ny, nz])

        # Scale radii (mm -> scene radius)
        norm_radii = [round(r / SCALE_FACTOR, 4) for r in raw_radii]
        avg_radius = round(sum(norm_radii) / max(1, len(norm_radii)), 4) if norm_radii else 0.08

        # Find or assign color
        base_color = color_map.get(v_id, '#f43f5e' if system == 'LCA' else '#38bdf8')

        processed_vessels.append({
            'id': v_id,
            'name': name,
            'abbr': short,
            'system': system,
            'color': base_color,
            'radius': avg_radius,
            'radii': norm_radii,
            'points': norm_points,
            'segments': segments,
            'pointsCount': len(norm_points)
        })

    os.makedirs(os.path.dirname(OUTPUT_JSON), exist_ok=True)
    with open(OUTPUT_JSON, 'w') as f:
        json.dump({
            'meta': meta,
            'attribution': 'BodyParts3D 4.0, (c) Database Center for Life Science (DBCLS), CC BY 4.0',
            'vessels': processed_vessels
        }, f, indent=2)
    print(f"[Pipeline] ✓ Saved JSON manifest to {OUTPUT_JSON}")

    # Generate TypeScript module
    ts_code = f"""/**
 * Authentic Coronary Centerlines & Tapering Radii
 * Data Source: BodyParts3D 4.0 whole-body CT database, Database Center for Life Science (DBCLS)
 * License: Creative Commons Attribution 4.0 International (CC BY 4.0)
 * Generated by scripts/pipeline/build_bodyparts3d_coronary.py
 */

export interface BodyParts3DVessel {{
  id: string;
  name: string;
  abbr: string;
  system: 'LCA' | 'RCA';
  color: string;
  radius: number;
  radii: number[];
  points: [number, number, number][];
  segments: Array<{{
    id: string;
    syntax: number | string;
    name: string;
    arc: [number, number];
  }}>;
  pointsCount: number;
}}

export const BODYPARTS3D_ATTRIBUTION = {{
  source: 'BodyParts3D 4.0',
  author: 'Database Center for Life Science (DBCLS), Japan',
  license: 'Creative Commons Attribution 4.0 International (CC BY 4.0)',
  url: 'https://lifesciencedb.jp/bp3d/',
  isocentre_offset_mm: [20.026, -123.4, 1226.978]
}};

export const REAL_BODYPARTS3D_VESSELS: BodyParts3DVessel[] = {json.dumps(processed_vessels, indent=2)};
"""

    with open(OUTPUT_TS, 'w') as f:
        f.write(ts_code)
    print(f"[Pipeline] ✓ Generated TypeScript module at {OUTPUT_TS}")

if __name__ == '__main__':
    run_pipeline()
